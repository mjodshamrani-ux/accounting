import { createRequire } from 'node:module';
import { readFile, mkdir, writeFile, copyFile } from 'node:fs/promises';
import path from 'node:path';
import { createHash } from 'node:crypto';

// Static program/model assets only. No financial document is read by this build.
const require = createRequire(import.meta.url);
const tessRoot = path.dirname(require.resolve('tesseract.js/package.json'));
const tessRequire = createRequire(path.join(tessRoot, 'package.json'));
const coreRoot = path.dirname(
  tessRequire.resolve('tesseract.js-core/package.json'),
);
const out = 'public/ocr';
await mkdir(out, { recursive: true });
const sha = (bytes) => createHash('sha256').update(bytes).digest('hex');
const assets = {};
for (const [from, to] of [
  [path.join(tessRoot, 'dist/worker.min.js'), 'worker-vendor.js'],
  [
    path.join(coreRoot, 'tesseract-core-lstm.wasm.js'),
    'tesseract-core-lstm.wasm.js',
  ],
]) {
  const bytes = await readFile(from);
  assets[to] = sha(bytes);
  await writeFile(path.join(out, to), bytes);
}
const models = {};
for (const language of ['eng', 'ara']) {
  const root = path.dirname(
    require.resolve(`@tesseract.js-data/${language}/package.json`),
  );
  const bytes = await readFile(
    path.join(root, '4.0.0_best_int', `${language}.traineddata.gz`),
  );
  assets[`${language}.traineddata.gz`] = sha(bytes);
  models[language] = bytes.toString('base64');
}
// The language files are embedded in this static script. Tesseract receives
// in-memory Lang objects for loadLanguage; initialize still receives eng+ara.
// This deliberately avoids all fetch/IDB and the library's default CDN paths.
const bootstrap = `/* Generated local OCR worker; Tesseract.js 7.0.0. */
'use strict';
const encodedModels = ${JSON.stringify(models)};
const deny = () => { throw new Error('Network access is disabled in visual OCR.'); };
Object.defineProperty(self, 'fetch', { value: () => Promise.reject(new Error('Network access is disabled in visual OCR.')), writable: false, configurable: false });
for (const key of ['XMLHttpRequest', 'WebSocket', 'EventSource']) Object.defineProperty(self, key, { value: deny, writable: false, configurable: false });
const originalPostMessage = self.postMessage.bind(self);
self.postMessage = (message, ...rest) => originalPostMessage(message?.action === 'loadLanguage' && message.status === 'resolve' ? { ...message, data: 'eng+ara' } : message, ...rest);
const localLanguages = () => ['eng', 'ara'].map(code => ({ code, data: Uint8Array.from(atob(encodedModels[code]), c => c.charCodeAt(0)) }));
self.addEventListener('message', event => {
  const message = event.data;
  if (message?.action === 'loadLanguage') {
    message.payload = { langs: localLanguages(), options: { cacheMethod: 'none', gzip: true, lstmOnly: true } };
  }
});
`;
// The bootstrap Blob supplies the only script location as a constant. Relative
// importScripts would resolve against blob: rather than the application base.
const worker = bootstrap + `self.importScripts(self.__mizanOcrVendorUrl);\n`;
assets['worker.js'] = sha(worker);
await writeFile(path.join(out, 'worker.js'), worker);
for (const [from, to] of [
  [path.join(tessRoot, 'LICENSE.md'), 'TESSERACT-JS-LICENSE.txt'],
  [path.join(coreRoot, 'LICENSE'), 'TESSERACT-CORE-LICENSE.txt'],
]) {
  await copyFile(from, path.join(out, to));
}
await writeFile(
  'lib/reconciliation/visual-assets.ts',
  `// Generated by scripts/prepare-ocr-assets.mjs from pinned local packages.\nexport const VISUAL_ENGINE = Object.freeze(${JSON.stringify({ library: 'tesseract.js', version: '7.0.0', languages: 'eng+ara', assetHashes: assets }, null, 2)} as const);\n`,
);
console.log(
  'Prepared local OCR assets: pinned English/Arabic models; no data connections.',
);
