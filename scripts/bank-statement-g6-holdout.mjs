if (recordedFile) {
  const recorded = await json(path.join(root, recordedFile));
  assert.deepEqual(report.summary, recorded.summary, 'holdout outcome changed');
  assert.deepEqual(
    report.statements,
    recorded.statements,
    'holdout statements changed',
  );
}
