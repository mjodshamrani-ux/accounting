// BNK-PDF-1 G6 holdout: the product on statements from two producers it has
// never read (LibreOffice Writer and ReportLab), sealed before this script
// first ran. Nothing stops at the first difference: every statement is
// measured layer by layer and the outcome recorded as it comes.
//   1. reading: each printed line read from the PDF against the facts
//      (kind, page, dates, reference, amounts, balances; descriptions and
//      continuation text after NFKC and whitespace normalisation);
//   2. statement: status, pages, period, currency and layout against the
//      oracle's EXPECTED.json and the facts;
//   3. result: the matching against the cashbook, in the facts' keys, against
//      EXPECTED.json; the XLSX cashbooks of H01 and H07 as well as the CSV;
//   4. false automatic pairs over all twelve statements.
// With --assert=<results file under audit/> it also fails unless the outcome
// equals the recorded one, so that a recorded
// failure stays visible and a change in either direction is noticed.
//   node --experimental-strip-types scripts/bank-statement-g6-holdout.mjs [--assert=<results file>]
import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { spawnSync } from 'node:child_process';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const suite = path.join(root, 'audit/bank-statement-holdout-g6');
const frozen = path.join(suite, 'frozen');
const outDir =
  process.env.BNK_G6_HOLDOUT_DIR ??
  path.join(root, 'work/bank-statement-g6-holdout');
const sha = (b) => createHash('sha256').update(b).digest('hex');
const json = async (p) => JSON.parse(await readFile(p, 'utf8'));

// The seal: every file, the facts regenerated by stories.py, holdout.json.
const manifest = await json(path.join(frozen, 'INPUT-MANIFEST.json'));
for (const e of manifest.files)
  assert.equal(
    sha(await readFile(path.join(frozen, e.file))),
    e.sha256,
    e.file,
  );
const facts = spawnSync('python3', ['-B', path.join(suite, 'stories.py')], {
  encoding: 'utf8',
  maxBuffer: 64 * 1024 * 1024,
});
assert.equal(facts.status, 0, facts.stderr);
assert.equal(sha(facts.stdout), manifest.facts.sha256, 'facts differ');
assert.equal(
  sha(await readFile(path.join(suite, 'holdout.json'))),
  manifest.holdout.sha256,
  'holdout.json differs from the seal',
);
const stories = JSON.parse(facts.stdout).stories;
const expected = await json(path.join(frozen, 'EXPECTED.json'));
const holdout = await json(path.join(suite, 'holdout.json'));

const { readNativePdfWordSource } = await import(
  path.join(root, 'lib/reconciliation/pdf.ts')
);
const { readFile: readSource } = await import(
  path.join(root, 'lib/reconciliation/io.ts')
);
const { readBankStatementPdf } = await import(
  path.join(root, 'lib/reconciliation/bank-statement-native.ts')
);
const { matchBankStatement, readBankCashbookTable } = await import(
  path.join(root, 'lib/reconciliation/bank-statement-match.ts')
);

const words = (s) => s.normalize('NFKC').replace(/\s+/gu, ' ').trim();
const minor = (s) => Math.round(Number(s) * 100);
const sorted = (xs) => [...xs].sort((a, b) => (a < b ? -1 : a > b ? 1 : 0));
const pairKeys = (pairs) => sorted(pairs.map((p) => p.join('|')));
const groupKeys = (groups) =>
  sorted(
    groups.map(
      (g) => `${sorted(g.bank).join(',')}/${sorted(g.cash).join(',')}/${g.reason}`,
    ),
  );
const message = (e) => (e instanceof Error ? e.message : String(e));

/** Differences between the reading and the facts, first ones only. */
function readingDifferences(reading, story, source) {
  const out = [];
  const add = (d) => out.length < 12 && out.push(d);
  const printed = story.statement.pages.flatMap((p, i) =>
    p.lines.map((l) => ({ ...l, page: i + 1 })),
  );
  if (reading.lines.length !== printed.length)
    add(`lines ${reading.lines.length} != ${printed.length}`);
  for (const [i, fact] of printed.entries()) {
    const got = reading.lines[i];
    const where = `line ${i + 1} (${fact.kind}${fact.key ? ' ' + fact.key : ''})`;
    if (!got) {
      add(`${where}: missing`);
      break;
    }
    if (got.kind !== fact.kind || got.page !== fact.page) {
      add(`${where}: read as ${got.kind} on page ${got.page}`);
      continue;
    }
    const items = new Set(
      source.pages[got.page - 1].tokens.map((t) => t.item),
    );
    if (!got.items.length || !got.items.every((n) => items.has(n)))
      add(`${where}: citation outside its page`);
    const fields =
      fact.kind === 'movement'
        ? ['date', 'valueDate', 'reference', 'withdrawal', 'deposit', 'balance']
        : fact.kind === 'totals' || fact.kind === 'page-totals'
          ? ['withdrawal', 'deposit']
          : fact.kind === 'continuation'
            ? []
            : ['balance'];
    for (const f of fields)
      if (got[f] !== fact[f])
        add(`${where} ${f}: ${JSON.stringify(got[f])} != ${JSON.stringify(fact[f])}`);
    if (fact.kind === 'movement' && words(got.description) !== words(fact.description))
      add(`${where} description: ${JSON.stringify(got.description)}`);
    if (fact.kind === 'continuation' && words(got.text) !== words(fact.text))
      add(`${where} text: ${JSON.stringify(got.text)}`);
  }
  return out;
}

/** The engine's result in the facts' keys. */
function inKeys(result, story) {
  const statementKeys = story.statement.pages
    .flatMap((p) => p.lines)
    .filter((l) => l.kind === 'movement')
    .map((l) => l.key);
  const s = (id) => statementKeys[Number(id.slice(1)) - 1] ?? `?${id}`;
  const voucher = new Map(story.cashbook.map((r) => [r.voucher, r.key]));
  const c = (id) => voucher.get(id) ?? `?${id}`;
  return {
    auto: result.auto.map((a) => [s(a.statement), c(a.cashbook)]),
    review: result.review.map((g) => ({
      bank: g.statement.map(s),
      cash: g.cashbook.map(c),
      reason: g.reason,
    })),
    bankOnly: result.statementOnly.map(s),
    cashOnly: result.cashbookOnly.map(c),
    timing: result.timing.map(s),
  };
}

function resultOutcome(result, story, want) {
  if (want.statement !== 'verified') {
    const approved = result.auto.length;
    return {
      equal:
        !!result.held &&
        result.held.statement === want.held.bank &&
        result.held.cashbook === want.held.cash &&
        ['auto', 'review', 'statementOnly', 'cashbookOnly', 'timing'].every(
          (k) => result[k].length === 0,
        ),
      held: result.held?.reason ?? null,
      falseAutomatic: approved,
      differences: result.held ? [] : ['not held'],
    };
  }
  if (result.held)
    return {
      equal: false,
      held: result.held.reason,
      falseAutomatic: 0,
      differences: [`held: ${result.held.reason}`],
    };
  const got = inKeys(result, story);
  const differences = [];
  if (pairKeys(got.auto).join() !== pairKeys(want.auto).join())
    differences.push(`auto ${got.auto.length} vs ${want.auto.length}`);
  if (groupKeys(got.review).join() !== groupKeys(want.review).join())
    differences.push(
      `review ${JSON.stringify(groupKeys(got.review))} vs ${JSON.stringify(groupKeys(want.review))}`,
    );
  for (const k of ['bankOnly', 'cashOnly', 'timing'])
    if (sorted(got[k]).join() !== sorted(want[k]).join())
      differences.push(`${k} ${JSON.stringify(got[k])} vs ${JSON.stringify(want[k])}`);
  const allowed = new Set(want.auto.map((p) => p.join('|')));
  return {
    equal: differences.length === 0,
    held: null,
    falseAutomatic: got.auto.filter((p) => !allowed.has(p.join('|'))).length,
    differences,
  };
}

async function cashbookOf(file, currency) {
  const bytes = await readFile(path.join(frozen, file));
  return readBankCashbookTable(
    await readSource(file, Uint8Array.from(bytes).buffer),
    currency,
  );
}

const statements = [];
for (const story of stories) {
  const id = story.id;
  const want = expected.stories.find((s) => s.id === id);
  const row = { id, producer: story.producer, layout: story.layout };
  statements.push(row);
  let source, reading;
  try {
    const bytes = await readFile(path.join(frozen, `${id}-statement.pdf`));
    source = await readNativePdfWordSource(Uint8Array.from(bytes).buffer);
    reading = readBankStatementPdf(source);
  } catch (e) {
    row.refused = message(e);
    row.reading = { ok: false, differences: [`refused: ${message(e)}`] };
    continue;
  }
  const differences = readingDifferences(reading, story, source);
  row.reading = { ok: differences.length === 0, differences };
  row.statement = {
    status: reading.status,
    expected: want.statement,
    reason: reading.reason ?? null,
    pages: reading.pages.length,
    period: reading.period,
    periodOk:
      JSON.stringify(reading.period) === JSON.stringify(story.statement.period),
    currency: reading.currency,
    layout: reading.layout,
    layoutOk: reading.layout === story.layout,
  };
  if (want.statement === 'verified')
    Object.assign(row.statement, {
      openingOk: reading.opening === minor(want.opening),
      closingOk: reading.closing === minor(want.closing),
    });
  for (const [label, file] of [
    ['csv', `${id}-cashbook.csv`],
    ...(story.cashbookXlsx ? [['xlsx', `${id}-cashbook.xlsx`]] : []),
  ]) {
    try {
      const cashbook = await cashbookOf(file, reading.currency);
      const outcome = resultOutcome(matchBankStatement(reading, cashbook), story, want);
      row[label] = { cashbookRows: cashbook.length, ...outcome };
    } catch (e) {
      row[label] = { refused: message(e), equal: false, falseAutomatic: 0 };
    }
  }
}

const eligible = holdout.eligibility.positives;
const positive = (r) =>
  !r.refused &&
  r.reading.ok &&
  r.statement.status === 'verified' &&
  r.csv?.equal === true &&
  (!stories.find((s) => s.id === r.id).cashbookXlsx || r.xlsx?.equal === true);
const report = {
  schema: 'tarasuf-bnk-pdf1-holdout-run/1',
  commit: spawnSync('git', ['rev-parse', 'HEAD'], { cwd: root, encoding: 'utf8' }).stdout.trim(),
  productSourceChanged: spawnSync(
    'git',
    ['status', '--porcelain', '--', 'lib', 'components', 'app', 'hooks'],
    { cwd: root, encoding: 'utf8' },
  ).stdout.trim() !== '',
  summary: {
    positivesCompleted: statements.filter((r) => eligible.includes(r.id) && positive(r)).map((r) => r.id),
    positivesFailed: statements.filter((r) => eligible.includes(r.id) && !positive(r)).map((r) => r.id),
    eligiblePositives: eligible.length,
    heldCorrectly: statements
      .filter((r) => r.id in holdout.eligibility.held)
      .filter((r) => !r.refused && r.statement.status === holdout.eligibility.held[r.id] && r.csv?.equal)
      .map((r) => r.id),
    readingOk: statements.filter((r) => r.reading.ok).map((r) => r.id),
    refused: statements.filter((r) => r.refused).map((r) => r.id),
    falseAutomatic: statements.reduce(
      (t, r) => t + (r.csv?.falseAutomatic ?? 0) + (r.xlsx?.falseAutomatic ?? 0),
      0,
    ),
  },
  statements,
};
await mkdir(outDir, { recursive: true });
await writeFile(path.join(outDir, 'run.json'), `${JSON.stringify(report, null, 1)}\n`);
console.log(JSON.stringify({ out: path.join(outDir, 'run.json'), ...report.summary }));
