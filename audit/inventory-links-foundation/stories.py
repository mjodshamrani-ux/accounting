# Dense stories: fixed rules, no randomness. Each kth item is broken in a
# named way, and the intent says so.
def dense():
    out = []

    def build(sid, title, n, accounts, sc, breaks=(), writers=("py-min", "py-all-bom", "py-min-crlf", "join"),
              dims=lambda k: f"warehouse=W{k % 7};bin=B{k % 13};lot=L{k % 101}", code=lambda k: f"SKU-{k:06d}",
              extra_gl=0, drop_gl=0):
        s = Story(sid, title, sc, writers=writers)
        for k in range(n):
            acct = f"13{k % accounts:02d}"
            rule = next((r for every, r in breaks if k % every == every - 1), None)
            item, dim = code(k), dims(k)
            if rule is None:
                s.item(item, dim, qty=str(k % 50 + 1), value=money(1000 + k % 977, s.dec), acct=acct)
            elif rule == "NO_MAPPING":
                s.item(item, dim, mapping=False, evidence=False, acct=acct, link=("unlinked", ["NO_MAPPING"]))
            elif rule == "NO_EVIDENCE":
                s.item(item, dim, evidence=False, acct=acct, link=("unlinked", ["NO_EVIDENCE"]))
            elif rule == "EVIDENCE_UNIT":
                s.item(item, dim, unit="BOX", ev_over={"Unit": "EA"}, acct=acct, link=("unlinked", ["EVIDENCE_UNIT"]))
            elif rule == "EVIDENCE_VALUATION":
                s.item(item, dim, val=f"VR-{k}", ev_over={"Valuation reference": f"VR-{k}-OLD"}, acct=acct,
                       link=("unlinked", ["EVIDENCE_VALUATION"]))
            elif rule == "EVIDENCE_ACCOUNT":
                s.item(item, dim, acct=acct, ev_over={"GL account": "1399"}, link=("unlinked", ["EVIDENCE_ACCOUNT"]))
            elif rule == "MAPPINGS":
                s.item(item, dim, acct=acct, link=("unlinked", ["MAPPINGS"]))
                s.rows[1].append([f"MP-DUP-{k}", item, dim, acct, "branch=01", s.rows[1][-1][5]])
            elif rule == "EVIDENCES":
                s.item(item, dim, acct=acct, link=("unlinked", ["EVIDENCES"]))
                e = list(s.rows[2][-1]); e[13] = f"POLICY-DUP-{k}"; s.rows[2].append(e)
        keys = list(s.glsum)
        for key in keys[drop_gl:]:
            s.gl(*key)
        for j in range(extra_gl):
            s.gl(f"14{j:02d}", "branch=01", debit=money(100 * (j + 1), s.dec))
        return s

    s = build("D1", "1,000 items, every row linked", 1000, 40, scope(n=31))
    s.financial = "ready"; out.append(s)

    zero = lambda k: f"{k:07d}"
    dims12 = lambda k: ";".join(f"d{p:02d}=v{(k + p) % (p + 3)}" for p in range(1, 13))
    s = build("D2", "5,000 items, twelve dimension parts, leading zeros, 5% unlinked without a source error", 5000, 50,
              scope(n=32), code=zero, dims=dims12,
              breaks=((97, "NO_MAPPING"), (89, "NO_EVIDENCE"), (83, "EVIDENCE_UNIT"), (79, "EVIDENCE_VALUATION"),
                      (73, "EVIDENCE_ACCOUNT")),
              writers=("py-all-bom", "py-min", "join", "py-min-crlf"))
    s.financial = "missing"; out.append(s)

    s = build("D3", "6,658 items and 26 GL rows: exactly 20,000 data rows, every row linked", 6658, 26,
              scope(n=33), writers=("py-min-crlf", "join", "py-all-bom", "py-min"))
    s.financial = "ready"; out.append(s)

    s = build("D4", "the same with 27 GL rows: 20,001 data rows, refused", 6658, 26, scope(n=34), extra_gl=1)
    s.refused = "ROWS"; s.financial = None; out.append(s)

    s = build("D5", "6,000 items, every reason, an unused GL row and an account without one", 6000, 30, scope(n=35),
              breaks=((211, "MAPPINGS"), (199, "EVIDENCES"), (101, "NO_MAPPING"), (97, "NO_EVIDENCE"),
                      (89, "EVIDENCE_UNIT"), (83, "EVIDENCE_VALUATION"), (79, "EVIDENCE_ACCOUNT")),
              extra_gl=1, drop_gl=1)
    s.financial = "source-error"
    missing_account = list(s.glsum)[0]
    s.unlinked = [["gl", len(s.rows[3]) + 1, f"1400|branch=01", "NO_LINKED_REGISTER"],
                  ["account", None, f"{missing_account[0]}|{missing_account[1]}", "NO_GL_RECORD"]]
    out.append(s)
    return out


def main():
    stories = [s.to_json() for s in focused()]
    json.dump({"schema": "tarasuf-inv3-stories/1", "stories": stories}, sys.stdout, ensure_ascii=False, indent=None)
    sys.stdout.write("\n")


if __name__ == "__main__":
    main()
