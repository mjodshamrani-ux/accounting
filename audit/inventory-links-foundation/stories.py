FIELDS = ["entity", "inventoryLedger", "glLedger", "currency", "currencyBasis",
          "postingStatus", "postingLayer", "asOf", "chartVersion", "mapVersion",
          "valuationPolicyVersion", "inventoryAccountSetVersion"]
SCOPE_HEADERS = ["Entity", "Inventory ledger", "GL ledger", "Currency", "Currency basis",
                 "Posting status", "Posting layer", "As of", "Chart version", "Map version",
                 "Valuation policy version", "Inventory account set version"]
VALUES = [
    ["Item ID", "Item dimensions", "Quantity", "Unit", "Quantity precision", "Posted value", "Valuation reference"],
    ["Mapping ID", "Item ID", "Item dimensions", "GL account", "GL dimensions", "Evidence ID"],
    ["Evidence ID", "Item ID", "Item dimensions", "Unit", "Quantity precision", "Valuation reference",
     "GL account", "GL dimensions", "Account class", "Sign", "Value basis", "Valid from", "Valid to", "Reference"],
    ["GL account", "GL dimensions", "Account class", "Debit", "Credit"],
]
ROLES = ["register", "mapping", "evidence", "gl"]
DECIMALS = {"SAR": 2, "KWD": 3, "JPY": 0}


def scope(entity="Synthetic Tile Wholesale Co", currency="SAR", as_of="2026-09-30", n=1):
    return {
        "entity": entity, "inventoryLedger": f"STK-{n}", "glLedger": f"GL-{n}", "currency": currency,
        "currencyBasis": "functional", "postingStatus": "posted", "postingLayer": "Close",
        "asOf": as_of, "chartVersion": f"COA-{n}", "mapVersion": f"MAP-{n}",
        "valuationPolicyVersion": f"VAL-{n}", "inventoryAccountSetVersion": f"SET-{n}",
    }


def minor(text, decimals):
    whole, _, frac = text.partition(".")
    return int(whole) * 10 ** decimals + int((frac + "0" * decimals)[:decimals] or 0)


def money(n, decimals):
    if not decimals:
        return str(n)
    return f"{n // 10 ** decimals}.{n % 10 ** decimals:0{decimals}d}"


class Story:
    def __init__(self, sid, title, sc, writers=("py-min", "py-all-bom", "node", "join"), orders=None):
        self.id, self.title, self.scope = sid, title, sc
        self.dec = DECIMALS[sc["currency"]]
        self.writers = list(writers)
        self.orders = orders or [None] * 4
        self.rows = [[], [], [], []]
        self.raw = [[], [], [], []]
        self.links = []
        self.unlinked = []
        self.financial = None
        self.refused = None
        self.glsum = {}

    # A register row, and by default its own mapping and evidence; `link` is
    # the intent written by hand for that row.
    def item(self, item, dims, qty="10", unit="EA", prec="0", value=None, val=None,
             acct="1310", gdims="branch=01", mapping=True, evidence=True,
             ev_over=None, link=("linked", []), mid=None, eid=None, count=True):
        value = value or money(1000 * 10 ** self.dec // 100 + 7 * len(self.rows[0]), self.dec)
        val = val or f"VR-{item}-{dims}"[:60]
        eid = eid or f"EV-{len(self.rows[0]) + 1:05d}"
        mid = mid or f"MP-{len(self.rows[0]) + 1:05d}"
        self.rows[0].append([item, dims, qty, unit, prec, value, val])
        if mapping:
            self.rows[1].append([mid, item, dims, acct, gdims, eid])
        if evidence:
            e = [eid, item, dims, unit, prec, val, acct, gdims, "inventory", "debit-positive",
                 "provided-posted-carrying-value", "2026-01-01", "2027-12-31", f"POLICY-{eid}"]
            for k, v in (ev_over or {}).items():
                e[VALUES[2].index(k)] = v
            self.rows[2].append(e)
        self.links.append([len(self.rows[0]) + 1, link[0], list(link[1])])
        if link[0] == "linked" and count:
            self.glsum[(acct, gdims)] = self.glsum.get((acct, gdims), 0) + minor(value, self.dec)
        return self

    def gl(self, acct, gdims, debit=None, credit=None, delta=0):
        d = debit if debit is not None else money(self.glsum.get((acct, gdims), 0) + delta, self.dec)
        self.rows[3].append([acct, gdims, "inventory", d, credit or money(0, self.dec)])
        return self

    def gls(self, delta=None):
        for k in self.glsum:
            self.gl(*k, delta=(delta or {}).get(k, 0))
        return self

    def to_json(self):
        files = []
        for i in range(4):
            header = VALUES[i] + SCOPE_HEADERS
            body = [r + [self.scope[f] for f in FIELDS] for r in self.rows[i]] + self.raw[i]
            order = self.orders[i]
            if order:
                header = [header[j] for j in order]
                body = [[r[j] for j in order] if len(r) == len(order) else r for r in body]
            files.append({"role": ROLES[i], "writer": self.writers[i], "rows": [header] + body})
        return {"id": self.id, "title": self.title, "scope": self.scope, "files": files,
                "intent": {"refused": self.refused, "financial": self.financial,
                           "links": self.links, "unlinked": self.unlinked}}


