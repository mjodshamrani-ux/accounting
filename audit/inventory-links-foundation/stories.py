"""INV-3 foundation stories: the flat inventory family's four files, and the
intent written by hand for each: every register row linked or unlinked with
its reasons, every unlinked mapping, evidence or GL row and account, and the
financial outcome the family gives today.

Synthetic only. Focused stories L01 to L26 are written to files and frozen;
dense stories D1 to D5 are generated by dense() from fixed rules, written by
render.py with Python writers only, and sealed by the hash of every file, so
CI regenerates them byte for byte instead of storing megabytes.

    python3 -B stories.py > frozen/stories.json
"""
