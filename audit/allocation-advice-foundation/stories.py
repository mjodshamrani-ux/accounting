"""ALL-1 foundation stories: one allocation snapshot per story (available
payments, open invoices and a remittance advice, each a CSV or XLSX file),
the accountant's decisions already taken, and the intent written by hand:
for every advice line its status, every reason it needs review, the other
open lines it competes with and its twins. Capacities, allocations and the
advice on each payment and invoice are the story's own arithmetic.

Synthetic only. Focused stories F01 to F33 are written to files and frozen;
dense stories D1 to D3 are generated by dense() from fixed rules, written by
render.py with Python's csv module only, and sealed by the hash of every
file, so CI regenerates them byte for byte instead of storing megabytes.

    python3 -B stories.py > frozen/stories.json
"""
import json
import sys

META = ["Entity", "Ledger", "Party", "Account", "Currency", "Snapshot date", "Allocation basis"]
HEADERS = [
    ["Payment ID", "Payment date", *META, "Original amount", "Available amount"],
    ["Invoice ID", "Invoice date", *META, "Original amount", "Available amount"],
    ["Advice line ID", *META, "Payment ID", "Invoice ID", "Allocation amount"],
]
ROLES = ["available-payments", "open-invoices", "proposed-remittance"]
DECIMALS = {"SAR": 2, "KWD": 3, "JPY": 0}
LIMIT = 20030  # rows in a sheet the reader admits, the header included
OP, OI, CP, CI, TW = "OVER_PAYMENT", "OVER_INVOICE", "COMPETES_PAYMENT", "COMPETES_INVOICE", "TWIN"


def money(minor, decimals):
    if not decimals:
        return str(minor)
    return f"{minor // 10 ** decimals}.{minor % 10 ** decimals:0{decimals}d}"


class Story:
    def __init__(self, sid, title, writer="py-min", currency="SAR", party="Supplier S01", orders=None):
        self.id, self.title, self.writer = sid, title, writer
        self.dec = DECIMALS[currency]
        self.scope = {"entity": "Synthetic Buyer Trading Co", "ledger": "AP-2026", "party": party,
                      "account": "2100", "currency": currency, "cutoff": "2026-09-30",
                      "basis": "before-proposed-allocation", "confirmed": True}
        # Column order per file: a permutation of the family's headers.
        self.orders = orders or [list(range(len(h))) for h in HEADERS]
        self.rows = [[], [], []]  # data rows, in the family's column order
        self.items = [{}, {}]  # reference -> [row, available]
        self.lines = {}  # line id -> [row, payment, invoice, amount]
        self.decisions = []
        self.hidden = [[], [], []]
        self.refused = None
        self.intent_lines = []

    def meta(self, overrides=None):
        s = self.scope
        values = [s["entity"], s["ledger"], s["party"], s["account"], s["currency"], s["cutoff"], s["basis"]]
        for k, v in (overrides or {}).items():
            values[META.index(k)] = v
        return values

    def _add(self, side, cells):
        self.rows[side].append(cells)
        return len(self.rows[side]) + 1

    def pay(self, ref, original, available=None, date="2026-09-20", text=None, meta=None):
        available = original if available is None else available
        row = self._add(0, [ref, date, *self.meta(meta), *(text or [money(original, self.dec),
                                                                   money(available, self.dec)])])
        self.items[0][ref] = [row, available]
        return row

    def inv(self, ref, original, available=None, date="2026-08-15", text=None, meta=None):
        available = original if available is None else available
        row = self._add(1, [ref, date, *self.meta(meta), *(text or [money(original, self.dec),
                                                                   money(available, self.dec)])])
        self.items[1][ref] = [row, available]
        return row

    def advice(self, line, payment, invoice, minor, text=None, meta=None):
        row = self._add(2, [line, *self.meta(meta), payment, invoice, text or money(minor, self.dec)])
        self.lines[line] = [row, payment, invoice, minor]
        return row

    def raw(self, side, cells):
        return self._add(side, list(cells))

    def remit(self, did, lines):
        self.decisions.append({"type": "remittance", "id": did, "lines": lines})
        return self

    def human(self, did, links, kind="accountant-review"):
        self.decisions.append({"type": "human", "id": did, "kind": kind, "links": links})
        return self

    def undo(self, did, target):
        self.decisions.append({"type": "undo", "id": did, "target": target})
        return self

    def line(self, lid, status, reasons=(), competitors=(), twins=()):
        """The hand-written intent for one advice line, by line IDs."""
        self.intent_lines.append([lid, status, list(reasons), list(competitors), list(twins)])
        return self

    def arithmetic(self):
        """Allocated per item from the story's own active decisions, and the
        open advice on each item."""
        active = {}
        for d in self.decisions:
            if d["type"] == "undo":
                active.pop(d["target"])
            elif d["type"] == "remittance":
                active[d["id"]] = [(self.lines[x][1], self.lines[x][2], self.lines[x][3], x) for x in d["lines"]]
            else:
                active[d["id"]] = [(p, i, m, None) for p, i, m in d["links"]]
        allocated, used = [{}, {}], set()
        for links in active.values():
            for p, i, m, x in links:
                allocated[0][p] = allocated[0].get(p, 0) + m
                allocated[1][i] = allocated[1].get(i, 0) + m
                if x:
                    used.add(x)
        advised = [{}, {}]
        for x, (_, p, i, m) in self.lines.items():
            if x not in used:
                advised[0][p] = advised[0].get(p, 0) + m
                advised[1][i] = advised[1].get(i, 0) + m
        out = []
        for side in (0, 1):
            for ref, (row, available) in self.items[side].items():
                a = allocated[side].get(ref, 0)
                out.append([side, ref, available - a, advised[side].get(ref, 0)])
        return out

    def to_json(self):
        xlsx = self.writer == "exceljs"
        names = [f"{self.id}-{k}.{'xlsx' if xlsx else 'csv'}" for k in ("payments", "invoices", "advice")]
        cells = []
        for side in range(3):
            order = self.orders[side]
            cells.append([[HEADERS[side][c] for c in order]] + [[r[c] for c in order] for r in self.rows[side]])
        row_of = {x: v[0] for x, v in self.lines.items()}
        if self.refused:
            intent = {"refused": self.refused, "lines": [], "items": []}
        else:
            intent = {"refused": None,
                      "lines": [[row_of[x], st, rs, sorted(row_of[c] for c in cs), sorted(row_of[t] for t in ts)]
                                for x, st, rs, cs, ts in sorted(self.intent_lines, key=lambda v: row_of[v[0]])],
                      "items": self.arithmetic()}
        return {"id": self.id, "title": self.title, "writer": self.writer, "names": names, "scope": self.scope,
                "decimals": self.dec, "cells": cells, "hidden": self.hidden,
                "lineRows": row_of, "adviceMinor": {x: v[3] for x, v in self.lines.items()}, "itemRows": [{r: v[0] for r, v in self.items[s].items()} for s in (0, 1)],
                "decisions": self.decisions, "intent": intent}


