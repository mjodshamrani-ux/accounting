    for t in range(29):
        k = 1 + t * 345
        n += 1
        s.advice(f"L{n:05d}", f"P{(t * 7) % 5000 + 1:04d}", f"I{k:05d}", 1)
    s.dense = {"over": [1 + t * 345 for t in range(29)]}
    out.append(s)
