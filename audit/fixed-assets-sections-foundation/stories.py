def dense():
    """D1: a register of exactly 20,001 records, 49 sections of four categories in seven places, 4,890
    assets, one of them with a carrying amount that does not add up. D2: the same with one blank record
    more inside the last section, refused before any review."""
    places = ["Riyadh HQ", "Jeddah depot", "Dammam yard", "Abha branch", "Tabuk branch", "Hail branch",
              "Qassim branch"]
    cats = ["Vehicles", "Furniture", "IT equipment", "Buildings"]
    out = []
    for sid in ("D1", "D2"):
        s = Story(sid, "A register at the reader's record ceiling" if sid == "D1"
                  else "One blank record over the ceiling", "py-min")
        n = 0
        for k in range(49):
            cat, place = cats[k % 4], places[k % 7]
            size = 100 if k < 48 else 90
            s.open(f"S-{k + 1:03d}", place, cat)
            for i in range(size):
                cost = 100000 + (n * 7919) % 9000000
                dep = (cost * ((n % 9) + 1)) // 12
                imp = (cost // 50) if n % 13 == 0 else 0
                a = [f"FA-{n + 1:05d}", f"CC-{100 + k % 5}", cost, dep, imp]
                if n == 4321:
                    s.asset(a, carrying=cost - dep - imp + 1, held=["CARRYING"])
                else:
                    s.asset(a)
                n += 1
            if sid == "D2" and k == 48:
                s.blank()
            s.close()
        s.standard_map(*cats)
        s.gl_consistent()
        bad = next(sec["category"] for sec in s.sections for a in sec["assets"] if a["held"])
        for c in ("cost", "depreciation", "impairment"):
            s.expect(ACCOUNTS[bad][c], "held", ["CARRYING"])
        if sid == "D2":
            s.refused = "CAPACITY"
        out.append(s)
    return out


def dense_intent(s):
    got = s.intent()
    if got["refused"]:
        return {"refused": got["refused"]}
    return {"refused": None, "records": len(s.files[0]), "sections": len(got["sections"]),
            "assets": len(got["assets"]), "held": sorted(k for k, v in got["assets"].items() if v[0] == "held"),
            "accounts": {k: v[:5] for k, v in got["accounts"].items()}}


