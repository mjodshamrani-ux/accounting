class Story:
    def __init__(self, sid, title, writer="py-min", currency="SAR", entity=ENTITY):
        self.id, self.title, self.writer = sid, title, writer
        self.places = PLACES.get(currency, 2)
        self.scope = {"entity": entity, "assetLedger": "FA-MAIN", "glLedger": "GL-2027", "currency": currency,
                      "asOf": "2027-12-31", "confirmed": True}
        self.files = [[], [list(MAP_HEADER)], [list(GL_HEADER)]]
        self.kinds = [[], ["header"], ["header"]]
        self.readings = [{"sheet": 0, "role": role, "family": FAMILY, "confirmed": True} for role in ROLES]
        self.cur = None
        self.sections = []
        self.placed = {}
        self.gl_written = {}
        self.refused = None
        self.run, self.unmapped, self.unplaced = [], [], []
        self.account_intent = {}
        self.patch = []

    # ----- register
    def put(self, cells, kind):
        self.files[0].append(list(cells))
        self.kinds[0].append(kind)
        return len(self.files[0])

    def blank(self, side=0):
        self.files[side].append([])
        self.kinds[side].append("blank")
        return len(self.files[side])

    def open(self, sid, location, category, *, labels=None, order=None, columns=COLUMNS, extra=(),
             status="read", codes=(), shown=None):
        """A section: its Section record, its label records and its column row. labels overrides a
        label's value (None omits it); extra adds records before the column row; shown gives the
        [Location, Category] the result names when a label does not read."""
        values = {"Entity": self.scope["entity"], "Asset ledger": self.scope["assetLedger"],
                  "Currency": self.scope["currency"], "As of": self.scope["asOf"], "Location": location,
                  "Category": category}
        values.update(labels or {})
        row = self.put(["Section", sid], "section")
        for label in order or LABELS:
            if values.get(label) is not None:
                self.put([label, values[label]], "label")
        for cells in extra:
            self.put(cells, "label")
        if columns is not None:
            self.put(list(columns), "columns")
        loc, cat = shown if shown is not None else (location, category)
        self.cur = {"id": sid, "row": row, "end": None, "location": loc, "category": cat,
                    "columns": list(columns or COLUMNS), "assets": [], "status": status, "codes": sorted(codes),
                    "judged": not (set(codes) & NOT_JUDGED)}
        self.sections.append(self.cur)
        return row

    def record(self, fields, extra=(), cells=None):
        if cells is None:
            cells = [fields[c] for c in self.cur["columns"]] + list(extra)
        return self.put(cells, "record")

    def asset(self, a, *, cost=None, dep=None, imp=None, carrying=None, val=None, order=COMPONENTS, omit=(),
              text=None, word=None, vals=None, repeat=None, held=(), drop=False, extra=None):
        """The four component rows of one asset. text gives an amount's written text; word the component
        written; vals a row's valuation reference; repeat adds rows {component: [amounts]}; extra a row's
        cells past the columns; held the codes the asset is expected to carry."""
        aid, dims = a[0], a[1]
        amounts = {"cost": a[2] if cost is None else cost, "depreciation": a[3] if dep is None else dep,
                   "impairment": a[4] if imp is None else imp}
        amounts["carrying"] = (amounts["cost"] - amounts["depreciation"] - amounts["impairment"]
                               if carrying is None else carrying)
        val = val or f"VAL-2027-{aid[:3]}"
        text, word, vals, extra = text or {}, word or {}, vals or {}, extra or {}
        rows = {}
        if not drop:
            for c in order:
                if c in omit:
                    continue
                fields = {"Asset ID": aid, "Asset dimensions": dims, "Component": word.get(c, c),
                          "Amount": text.get(c, money(amounts[c], self.places)),
                          "Valuation reference": vals.get(c, val)}
                rows.setdefault(c, []).append(self.record(fields, extra.get(c, ())))
                for more in (repeat or {}).get(c, []):
                    fields = dict(fields, Amount=money(more, self.places))
                    rows[c].append(self.record(fields))
            self.cur["assets"].append({"id": aid, "dims": dims, "amounts": amounts, "held": sorted(held)})
        return rows

    def total(self, component, minor=None, text=None):
        return self.put(["Section total", component, text if text is not None else money(minor, self.places)],
                        "total")

    def section_total(self, component, assets):
        key = {"cost": 2, "depreciation": 3, "impairment": 4}
        if component == "carrying":
            return self.total(component, sum(a[2] - a[3] - a[4] for a in assets))
        return self.total(component, sum(a[key[component]] for a in assets))

    def close(self, end_id=None, write=True):
        if write:
            self.cur["end"] = self.put(["End section", self.cur["id"] if end_id is None else end_id], "end")
        self.cur = None

    def section(self, sid, location, category, assets, *, totals=False, **kw):
        self.open(sid, location, category, **kw)
        for a in assets:
            self.asset(a)
        if totals:
            for c in COMPONENTS:
                self.section_total(c, assets)
        self.close()

    def hold_section(self, status, codes):
        self.sections[-1]["status"] = status
        self.sections[-1]["codes"] = sorted(codes)

    # ----- map
    def map_row(self, category, component, account=None, *, dims=DIMS, cls=None, frm="2020-01-01",
                to="9999-12-31", placed=True, cells=None):
        if cells is None and account is None:
            account = ACCOUNTS[category][component]
        row = cells or [category, component, account, dims, cls or CLASSES.get(component, "fixed-asset-cost"), frm,
                        to]
        self.files[1].append(list(row))
        self.kinds[1].append("row")
        if placed:
            self.placed[(category, component)] = (account, dims)
        return len(self.files[1])

    def standard_map(self, *categories, skip=()):
        for cat in categories:
            for c in ("cost", "depreciation", "impairment"):
                if (cat, c) not in skip:
                    self.map_row(cat, c)

    # ----- GL
    def gl_row(self, account, normal=None, *, dims=DIMS, cls=None, component=None, debit=None, credit=None,
               scope=None, cells=None):
        if cells is None:
            component = component or next(c for cat in ACCOUNTS.values() for c, a in cat.items() if a == account)
            cls = cls or CLASSES[component]
            if debit is None:
                if component == "cost":
                    debit, credit = (normal, 0) if normal >= 0 else (0, -normal)
                else:
                    debit, credit = (0, normal) if normal >= 0 else (-normal, 0)
                debit, credit = money(debit, self.places), money(credit, self.places)
            sc = {"Entity": self.scope["entity"], "GL ledger": self.scope["glLedger"],
                  "Currency": self.scope["currency"], "As of": self.scope["asOf"]}
            sc.update(scope or {})
            cells = [account, dims, cls, debit, credit, sc["Entity"], sc["GL ledger"], sc["Currency"], sc["As of"]]
        self.files[2].append(list(cells))
        self.kinds[2].append("row")
        if normal is not None:
            self.gl_written[(account, dims)] = normal
        return len(self.files[2])

    def members(self, account, dims=DIMS):
        out = []
        for s in self.sections:
            if not s["judged"]:
                continue
            for a in s["assets"]:
                for c in ("cost", "depreciation", "impairment"):
                    if self.placed.get((s["category"], c)) == (account, dims):
                        out.append([s["id"], a["id"], a["dims"], c])
        return sorted(out)

    def register_sum(self, account, dims=DIMS):
        total = 0
        for s in self.sections:
            if not s["judged"]:
                continue
            for a in s["assets"]:
                for c in ("cost", "depreciation", "impairment"):
                    if self.placed.get((s["category"], c)) == (account, dims):
                        total += a["amounts"][c]
        return total

    def gl_consistent(self, adjust=None, skip=(), **kw):
        """A GL row for every placed account, equal to the register sum the story intends, moved by adjust."""
        adjust = adjust or {}
        for account, dims in sorted(set(self.placed.values())):
            if account in skip:
                continue
            self.gl_row(account, self.register_sum(account, dims) + adjust.get(account, 0), dims=dims, **kw)

    # ----- intent
    def expect(self, account, status, codes=(), dims=DIMS):
        self.account_intent[(account, dims)] = [status, sorted(codes)]

    def judged_accounts(self):
        keys = set(self.placed.values())
        for row, kind in zip(self.files[2], self.kinds[2]):
            if kind == "row" and len(row) >= 2 and row[0] and row[1] and row[0][0] not in "=+@-":
                keys.add((row[0], row[1]))
        return sorted(keys)

    def intent(self):
        if self.refused:
            return {"refused": self.refused}
        accounts = {}
        for key in self.judged_accounts():
            status, codes = self.account_intent.get(key, ["consistent", []])
            members = self.members(*key)
            register = gl = difference = None
            if status != "held":
                register = self.register_sum(*key) if members else None
                gl = self.gl_written.get(key)
                if register is not None and gl is not None:
                    difference = register - gl
            accounts["|".join(key)] = [status, codes, register, gl, difference, members]
        assets = {}
        for s in self.sections:
            if s["judged"]:
                for a in s["assets"]:
                    assets["|".join([s["id"], a["id"], a["dims"]])] = ["held" if a["held"] else "read", a["held"]]
        return {
            "refused": None,
            "run": sorted(self.run),
            "sections": [[s["row"], s["end"], s["id"], s["location"], s["category"], s["status"], s["codes"]]
                         for s in self.sections],
            "assets": assets,
            "unmapped": sorted(self.unmapped),
            "accounts": accounts,
            "unplaced": sorted(self.unplaced, key=lambda u: (ROLES.index(u[0]), u[1])),
            "inventory": self.inventory(),
        }

    def inventory(self):
        reg = {k: 0 for k in ["blank", "section", "end", "stray", "label", "columns", "total", "record"]}
        for k in self.kinds[0]:
            reg[k] += 1
        flat = [{k: kinds.count(k) for k in ["header", "blank", "row"]} for kinds in self.kinds[1:]]
        return {"register": reg, "map": flat[0], "gl": flat[1]}

    def to_json(self):
        return {"id": self.id, "title": self.title, "writer": self.writer, "scope": self.scope,
                "readings": self.readings, "names": [f"{self.id}-{k}.csv" for k in KINDS], "cells": self.files,
                "patch": self.patch, "intent": self.intent()}


def base(s, *categories, gl=True):
    s.standard_map(*categories)
    if gl:
        s.gl_consistent()


