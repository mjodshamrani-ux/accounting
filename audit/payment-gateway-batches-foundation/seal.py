"""Seal the PG-1 foundation before any product run: every focused input by
hash, every dense file regenerated by render.py and its expectation by hash,
the expectations and the independent file check, and the tools that made
and judge them.

    python3 -B audit/payment-gateway-batches-foundation/seal.py
"""
import hashlib
import json
import subprocess
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
FROZEN = HERE / "frozen"
JUDGED = ["EXPECTED.json", "VERIFY.json", "DENSE-MANIFEST.json"]
TOOLS = ["contract.json", "stories.py", "render.py", "render.mjs", "oracle.py", "verify.py", "dense.py",
         "test_oracle.py", "mutate_oracle.py"]
NOT_INPUTS = {"INPUT-MANIFEST.json", "SEAL.json", *JUDGED}


def sha(path):
    return hashlib.sha256(Path(path).read_bytes()).hexdigest()


def manifest():
    files = sorted(p.name for p in FROZEN.iterdir() if p.name not in NOT_INPUTS)
    return {
        "schema": "tarasuf-pg1-batches-input-manifest/1",
        "synthetic": True,
        "producer": "stories.py facts; each transactions, fees, settlements, payout lines and bank credits file "
                    "written as CSV by Python csv (minimal quoting with LF or CRLF; every field quoted with a byte "
                    "order mark and CRLF) or as XLSX by ExcelJS 4.4.0 (text cells and hidden rows); each input as "
                    "JSON with the file names, the confirmed readings and the scope",
        "files": {name: {"sha256": sha(FROZEN / name), "bytes": (FROZEN / name).stat().st_size} for name in files},
    }


def dense_manifest():
    with tempfile.TemporaryDirectory() as tmp:
        subprocess.run([sys.executable, "-B", str(HERE / "render.py"), "--dense", tmp], check=True)
        files = {p.name: {"sha256": sha(p), "bytes": p.stat().st_size} for p in sorted(Path(tmp).iterdir())}
        judged = subprocess.run([sys.executable, "-B", str(HERE / "oracle.py"), "--dense", tmp], check=True,
                                capture_output=True).stdout
        checked = json.loads(subprocess.run([sys.executable, "-B", str(HERE / "verify.py"), "--dense", tmp],
                                            check=True, capture_output=True).stdout)
    summary = {}
    for sid, x in json.loads(judged)["stories"].items():
        count = lambda key: {s: sum(1 for v in x[key] if v["status"] == s)  # noqa: E731
                             for s in sorted({v["status"] for v in x[key]})}
        summary[sid] = {"refused": x["refused"], "batches": count("batches"), "payouts": count("payouts"),
                        "credits": len(x["credits"])}
    return {"schema": "tarasuf-pg1-dense-manifest/1", "synthetic": True,
            "producer": "stories.py dense(), fixed rules and no randomness, written by render.py --dense with Python "
                        "csv only; regenerated and checked by dense.py before any run",
            "files": files, "expectedSha256": hashlib.sha256(judged).hexdigest(), "summary": summary,
            "verify": checked}


def main():
    (FROZEN / "INPUT-MANIFEST.json").write_text(json.dumps(manifest(), indent=1) + "\n", encoding="utf-8")
    (FROZEN / "DENSE-MANIFEST.json").write_text(json.dumps(dense_manifest(), indent=1) + "\n", encoding="utf-8")
    seal = {
        "schema": "tarasuf-pg1-batches-seal/1",
        "statement": "Sealed before any product run on these files. The baseline that follows records the product as it is.",
        "pins": {name: sha(FROZEN / name) for name in ["INPUT-MANIFEST.json", *JUDGED]}
        | {name: sha(HERE / name) for name in TOOLS},
    }
    (FROZEN / "SEAL.json").write_text(json.dumps(seal, indent=1) + "\n", encoding="utf-8")
    print(json.dumps(seal["pins"], indent=1))


if __name__ == "__main__":
    main()
