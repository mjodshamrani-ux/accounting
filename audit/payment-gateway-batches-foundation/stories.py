def dense():
    """D1: 20,029 transactions over 40 batches paid by 14 payouts, two batches
    and one payout with a difference; D2: one transaction more, over the ceiling;
    D3: 4,000 batches each paid by its own payout, every twentieth credited
    after the period end and every hundredth never credited."""
    out = []
    s = Story("D1", "20,029 transactions at the reader's ceiling over 40 batches and 14 payouts")
    per = {}
    for n in range(LIMIT - 1):
        b = f"B{n % 40 + 1:02d}"
        amount = 1000 + (n * 37) % 9000
        if n % 9 == 8:
            s.refund(f"T{n + 1:05d}", b, amount // 2)
            per.setdefault(b, [0, 0])[1] += amount // 2
        else:
            s.sale(f"T{n + 1:05d}", b, amount)
            per.setdefault(b, [0, 0])[0] += amount
    for k in range(1, 41):
        b = f"B{k:02d}"
        s.fee(f"FE{k:02d}", b, 500 + k)
    for k in range(1, 41):
        b = f"B{k:02d}"
        gross, refunds = per[b]
        fees = 500 + k
        if k == 7:
            gross += 1  # the settlement row claims one halala more of sales
        s.settle(b, gross, refunds, fees)
    paid = {}
    for k in range(1, 41):
        b = f"B{k:02d}"
        gross, refunds = per[b]
        net = gross - refunds - (500 + k) + (1 if k == 7 else 0)
        payout = f"P{(k - 1) // 3 + 1:02d}"
        amount = net - 100 if k == 19 else net
        s.line(payout, b, amount)
        paid.setdefault(payout, 0)
        paid[payout] += amount
    for p in sorted(paid):
        credit = paid[p] + (5 if p == "P13" else 0)
        s.credit(f"BR{p[1:]}", p, credit)
    s.dense_rule = "D1"
    out.append(s)

    s = Story("D2", "20,030 transactions, one over the reader's ceiling")
    for n in range(LIMIT):
        s.sale(f"T{n + 1:05d}", "B1", 1000)
    s.settle("B1", 1000 * LIMIT, 0, 0); s.line("P1", "B1", 1000 * LIMIT); s.credit("BR1", "P1", 1000 * LIMIT)
    s.refuse("ROWS")
    out.append(s)

    s = Story("D3", "4,000 batches each paid by its own payout")
    for k in range(1, 4001):
        s.sale(f"T{k:04d}", f"B{k:04d}", 10000 + k)
    for k in range(1, 4001):
        s.settle(f"B{k:04d}", 10000 + k, 0, 0)
    for k in range(1, 4001):
        s.line(f"P{k:04d}", f"B{k:04d}", 10000 + k)
    for k in range(1, 4001):
        if k % 100 == 0:
            continue
        s.credit(f"BR{k:04d}", f"P{k:04d}", 10000 + k, date="2026-10-03" if k % 20 == 0 else "2026-09-25")
    s.dense_rule = "D3"
    out.append(s)
    return out


def dense_intent(s):
    """The dense stories' intent by their rules, written here and not by the
    oracle."""
    if s.id == "D2":
        return {"refused": "ROWS", "batches": [], "payouts": [], "credits": []}
    if s.id == "D1":
        members = {}
        for row, r in enumerate(s.rows[0], start=2):
            members.setdefault(r[1], [[], []])[0 if r[2] == "sale" else 1].append(row)
        batches = []
        for k in range(1, 41):
            reasons = []
            if k == 7:
                reasons = [SALES]  # the row claims one halala more of sales and adds up with it
            if k == 19:
                reasons = [SHORT]
            p = f"P{(k - 1) // 3 + 1:02d}"
            if p == "P13":
                reasons = reasons + [PAYOUT]
            line_row = k + 1
            paid = int(s.rows[3][k - 1][2].replace(".", ""))
            batches.append([k + 1, "review" if reasons else "consistent", reasons, members[f"B{k:02d}"][0],
                            members[f"B{k:02d}"][1], [k + 1], paid, [p]])
        payouts = []
        for j in range(1, 15):
            p = f"P{j:02d}"
            lines = [k + 1 for k in range(1, 41) if (k - 1) // 3 + 1 == j]
            payouts.append([p, "review" if p == "P13" else "consistent", [CREDIT] if p == "P13" else [], lines, j + 1])
        return {"refused": None, "batches": batches, "payouts": payouts, "credits": []}
    if s.id == "D3":
        batches, payouts, credit_row = [], [], {}
        row = 2
        for k in range(1, 4001):
            if k % 100:
                credit_row[k] = row
                row += 1
        for k in range(1, 4001):
            missing = k % 100 == 0
            late = k % 20 == 0 and not missing
            batches.append([k + 1, "review" if missing else "in-transit" if late else "consistent",
                            [PAYOUT] if missing else [], [k + 1], [], [], 10000 + k, [f"P{k:04d}"]])
            payouts.append([f"P{k:04d}", "review" if missing else "in-transit" if late else "consistent",
                            [MISSING] if missing else [], [k + 1], None if missing else credit_row[k]])
        return {"refused": None, "batches": batches, "payouts": payouts, "credits": []}
    raise ValueError(s.id)


