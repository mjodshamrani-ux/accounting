def money(minor, places):
    if not places:
        return str(minor)
    return f"{minor // 10 ** places}.{minor % 10 ** places:0{places}d}"


class Story:
    def __init__(self, sid, title, writer="py-min", currency="SAR", gateway="Synthetic Pay GW"):
        self.id, self.title, self.writer = sid, title, writer
        self.places = PLACES[currency]
        self.scope = {"entity": "Synthetic Souq Online Co", "gateway": gateway, "merchantAccount": "MA-7781",
                      "bankAccount": "BANK-0042", "currency": currency, "start": "2026-09-01",
                      "end": "2026-09-30", "asOf": "2026-10-10", "confirmed": True}
        self.headers = [list(h) for h in HEADERS]
        self.rows = [[], [], [], [], []]
        self.hidden = [[], [], [], [], []]
        self.refused = None
        self.intent_batches, self.intent_payouts, self.intent_credits = [], [], []

    def _put(self, side, cells):
        self.rows[side].append(list(cells))
        return len(self.rows[side]) + 1

    def _m(self, minor, text):
        return text if text is not None else money(minor, self.places)

    def sale(self, tid, batch, minor, date="2026-09-10", ref=None, text=None, kind="sale"):
        return self._put(0, [tid, batch, kind, date, self._m(minor, text), ref or f"Order {tid}", "MA-7781",
                             self.scope["currency"]])

    def refund(self, tid, batch, minor, date="2026-09-12", ref=None, text=None):
        return self.sale(tid, batch, minor, date, ref or f"Refund {tid}", text, kind="refund")

    def fee(self, fid, batch, minor, ref=None, text=None):
        return self._put(1, [fid, batch, self._m(minor, text), ref or f"Fee invoice {fid}", "MA-7781",
                             self.scope["currency"]])

    def settle(self, batch, gross, refunds, fees, net=None, date="2026-09-15", text=None):
        net = gross - refunds - fees if net is None else net
        cells = text or [money(v, self.places) for v in (gross, refunds, fees, net)]
        return self._put(2, [batch, date, *cells, "MA-7781", self.scope["currency"]])

    def line(self, payout, batch, minor, text=None):
        return self._put(3, [payout, batch, self._m(minor, text), "MA-7781", self.scope["currency"]])

    def credit(self, ref, payout, minor, date="2026-09-20", text=None):
        return self._put(4, [ref, payout, date, self._m(minor, text), "BANK-0042", self.scope["currency"]])

    def raw(self, side, cells):
        return self._put(side, cells)

    def order(self, side, headers):
        assert sorted(headers) == sorted(self.headers[side])
        at = [self.headers[side].index(h) for h in headers]
        self.headers[side] = list(headers)
        self.rows[side] = [[r[k] for k in at] if r else [] for r in self.rows[side]]
        return self

    def drop(self, side, header):
        k = self.headers[side].index(header)
        self.headers[side].pop(k)
        for r in self.rows[side]:
            if r:
                r.pop(k)
        return self

    def batch(self, row, status, reasons=(), sales=(), refunds=(), fees=(), paid=0, payouts=()):
        self.intent_batches.append([row, status, list(reasons), list(sales), list(refunds), list(fees), paid,
                                    list(payouts)])
        return self

    def payout(self, pid, status, reasons=(), lines=(), credit=None):
        self.intent_payouts.append([pid, status, list(reasons), list(lines), credit])
        return self

    def unlinked(self, row, pid):
        self.intent_credits.append([row, pid])
        return self

    def refuse(self, code):
        self.refused = code
        return self

    def to_json(self):
        xlsx = self.writer == "exceljs"
        names = [f"{self.id}-{k}.{'xlsx' if xlsx else 'csv'}" for k in KINDS]
        if self.refused:
            intent = {"refused": self.refused, "batches": [], "payouts": [], "credits": []}
        else:
            intent = {"refused": None, "batches": self.intent_batches, "payouts": self.intent_payouts,
                      "credits": self.intent_credits}
        return {"id": self.id, "title": self.title, "writer": self.writer, "names": names, "scope": self.scope,
                "decimals": self.places, "cells": [[self.headers[s]] + self.rows[s] for s in range(5)],
                "hidden": self.hidden, "intent": intent}


