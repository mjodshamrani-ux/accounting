"""PG-1 foundation stories: one review per story over five files (gateway
transactions, fee evidence, settlement rows, the gateway's payout lines and
the bank's credits), and the intent written by hand: for every batch its
status, every reason in contract order and its members by row, for every
payout its status, reasons, lines and credit, and every unlinked credit; or
the refusal of the whole story. Sums are the story's own arithmetic.

Synthetic only. Focused stories F01 to F35 are written to files and frozen;
dense stories D1 to D3 are generated by dense() from fixed rules, written by
render.py with Python's csv module only, and sealed by the hash of every
file, so CI regenerates them byte for byte instead of storing megabytes.

    python3 -B stories.py > frozen/stories.json
    python3 -B stories.py --dense          # the dense stories' facts
"""
