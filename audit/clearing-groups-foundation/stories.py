HEADER = ["Posting ID", "Clearing Reference", "Date", "Amount", "Account", "Currency", "Description"]
SPLIT_HEADER = ["Posting ID", "Clearing Reference", "Date", "Debit", "Credit", "Account", "Currency",
                "Description"]
SIGNED = {"sheet": 0, "header": 0, "posting": 0, "reference": 1, "date": 2, "amount": 3, "debit": -1,
          "credit": -1, "account": 4, "currency": 5, "description": 6, "mode": "signed"}
SPLIT = {"sheet": 0, "header": 0, "posting": 0, "reference": 1, "date": 2, "amount": -1, "debit": 3,
         "credit": 4, "account": 5, "currency": 6, "description": 7, "mode": "split"}
DECIMALS = {"SAR": 2, "KWD": 3, "JPY": 0}
LIMIT = 20030  # rows in a sheet the reader admits, the header included


def scope(currency="SAR", account="2150", start="2026-09-01", end="2026-09-30"):
    return {"entity": "Synthetic Clearing Trading Co", "ledger": "GL-2026", "account": account,
            "currency": currency, "start": start, "end": end, "confirmed": True}


def money(minor, decimals):
    sign, minor = ("-", -minor) if minor < 0 else ("", minor)
    if not decimals:
        return f"{sign}{minor}"
    return f"{sign}{minor // 10 ** decimals}.{minor % 10 ** decimals:0{decimals}d}"


class Extract:
    def __init__(self, sid, title, fmt="csv", writer="py-min", currency="SAR", header=None, split=False,
                 account="2150"):
        self.id, self.title, self.fmt, self.writer = sid, title, fmt, writer
        self.scope = scope(currency, account)
        self.dec = DECIMALS[currency]
        self.split = split
        self.reading = dict(SPLIT if split else SIGNED)
        self.rows = [list(header or (SPLIT_HEADER if split else HEADER))]
        self.hidden, self.formulas = [], {}
        self.amounts = {}
        self.groups, self.errors, self.blank = [], [], []
        self.refused = None

    def line(self, posting, ref, day, minor, desc="", account=None, currency=None, date=None, text=None):
        """One line; `minor` is the amount in minor units, `text` overrides
        its cell. Returns the physical row."""
        cell = text if text is not None else money(minor, self.dec)
        when = date or f"2026-09-{day:02d}"
        acc, cur = account or self.scope["account"], currency or self.scope["currency"]
        if self.split:
            debit = cell if text is not None or minor >= 0 else money(0, self.dec)
            credit = money(-minor, self.dec) if text is None and minor < 0 else money(0, self.dec)
            self.rows.append([posting, ref, when, debit, credit, acc, cur, desc])
        else:
            self.rows.append([posting, ref, when, cell, acc, cur, desc])
        self.amounts[len(self.rows)] = minor
        return len(self.rows)

    def raw(self, cells):
        self.rows.append(list(cells))
        return len(self.rows)

    def group(self, ref, rows, reasons=()):
        net = sum(self.amounts[r] for r in rows)
        self.groups.append([ref, list(rows), net, "review" if reasons else "cleared", list(reasons)])
        return self

    def error(self, row, code):
        self.errors.append([row, code])
        return self

    def to_json(self):
        return {"id": self.id, "title": self.title, "format": self.fmt, "writer": self.writer,
                "name": f"{self.id}.{self.fmt}", "reading": self.reading, "scope": self.scope,
                "cells": self.rows, "hidden": self.hidden,
                "formulas": [[r, c, f] for (r, c), f in sorted(self.formulas.items())],
                "intent": {"refused": self.refused, "groups": self.groups, "errors": self.errors,
                           "blank": self.blank}}


