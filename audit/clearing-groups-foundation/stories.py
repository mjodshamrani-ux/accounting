def dense():
    """Rows at and over the reader's ceiling, from fixed rules."""
    out = []
    lines = LIMIT - 1

    def triples(e, n, posting=lambda k, j: f"P{3 * k + j:05d}"):
        for k in range(n):
            ref = f"D{k:05d}"
            rows = [e.line(posting(k, 0), ref, 1 + k % 28, 3000 + k, "Invoice"),
                    e.line(posting(k, 1), ref, 1 + k % 28, -2000, "Payment part one"),
                    e.line(posting(k, 2), ref, 1 + k % 28, -(1000 + k), "Payment part two")]
            yield ref, rows

    e = Extract("D1", "every line at the ceiling, every group clean")
    for ref, rows in triples(e, lines // 3):
        e.group(ref, rows)
    for j in range(lines % 3):
        e.group("", [e.line(f"Q{j:05d}", "", 30, 100 * (j + 1), "Unreferenced")], [M])
    out.append(e)

    e = Extract("D2", "the ceiling, one faulty line in every thirty-three groups held with its group alone")
    n = (lines - lines // 100) // 3
    for ref, rows in triples(e, n):
        k = int(ref[1:])
        if k % 33 == 32:
            e.error(e.line(f"X{k:05d}", ref, 1 + k % 28, 0, "Faulty", text="?"), "AMOUNT_FORMAT")
            e.group(ref, rows, [C])
        else:
            e.group(ref, rows)
    while len(e.rows) - 1 < lines:
        j = len(e.rows)
        e.group("", [e.line(f"Q{j:05d}", "", 30, 100, "Unreferenced")], [M])
    out.append(e)

    e = Extract("D3", "the ceiling, one faulty line without a reference holds every group")
    groups = list(triples(e, (lines - 1) // 3))
    while len(e.rows) - 1 < lines - 1:
        j = len(e.rows)
        groups.append(("", [e.line(f"Q{j:05d}", "", 30, 100, "Unreferenced")]))
    e.error(e.line("X99999", "", 30, 0, "Faulty", text="?"), "AMOUNT_FORMAT")
    for ref, rows in groups:
        e.group(ref, rows, [U, M] if not ref else [U])
    out.append(e)

    e = Extract("D4", "one line over the ceiling")
    for ref, rows in triples(e, (lines + 1) // 3):
        pass
    while len(e.rows) - 1 < lines + 1:
        e.line(f"Q{len(e.rows):05d}", "", 30, 100, "Unreferenced")
    e.refused = "ROWS"
    out.append(e)

    e = Extract("D5", "the ceiling, every payment posting with three lines in three groups")
    n = lines // 2
    # Invoices first, then payment postings of three lines each, one line per group.
    for k in range(n):
        e.line(f"I{k:05d}", f"D{k:05d}", 1 + k % 28, 1000 + k, "Invoice")
    pay = {}
    for k in range(n):
        pay[k] = e.line(f"Y{k // 3:05d}", f"D{k:05d}", 29, -(1000 + k), "Payment batch line")
    for k in range(n):
        e.group(f"D{k:05d}", [k + 2, pay[k]])
    e.group("", [e.line("Q99999", "", 30, 100, "Unreferenced")], [M])
    out.append(e)
    return out


