"""CLR-1 foundation stories: one clearing account extract per story, CSV or
XLSX, and the intent written by hand: every group with its members by row,
its status and every reason it is not cleared, and every error row with its
code. Nets are the story's own arithmetic.

Synthetic only. Focused stories F01 to F32 are written to files and frozen;
dense stories D1 to D5 are generated by dense() from fixed rules, written by
render.py with Python's csv module only, and sealed by the hash of every
file, so CI regenerates them byte for byte instead of storing megabytes.

    python3 -B stories.py > frozen/stories.json
"""
